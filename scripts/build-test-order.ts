/**
 * Builds the frozen 4-part question order for a full-length test pack.
 *   npx tsx scripts/build-test-order.ts gt4 4
 * Writes src/data/tests/grandTest<N>.ts. Parts are balanced by difficulty
 * and subject (round-robin within each difficulty level).
 */
import { writeFileSync } from 'node:fs'
import { loadAllReserved, loadedReservedEntries } from '../src/data/reservedQuestions'

const [pack, num] = process.argv.slice(2)
if (!pack || !num) { console.error('Usage: build-test-order.ts <pack> <testNumber>'); process.exit(1) }
await loadAllReserved()
const entries = loadedReservedEntries().filter((e) => e.question.id.startsWith(`${pack}-`))
if (entries.length !== 200) { console.error(`${pack} has ${entries.length} questions; 200 required`); process.exit(1) }
const subjects = [...new Set(entries.map((e) => e.subject))]
const flat = (['Easy', 'Medium', 'Hard', 'Expert'] as const).flatMap((d) => subjects.flatMap((s) => entries.filter((e) => e.subject === s && e.question.difficulty === d)))
const parts: string[][] = [[], [], [], []]
flat.forEach((e, k) => parts[k % 4].push(e.question.id))
const body = parts.map((p, i) => `  // Part ${i + 1}\n` + p.map((id) => `  '${id}',`).join('\n')).join('\n')
writeFileSync(`src/data/tests/grandTest${num}.ts`, `/**
 * Grand Test ${num} (version 1) — frozen question order, generated by
 * scripts/build-test-order.ts. Split in order into Part 1–4 of 50; order inside
 * a part is shuffled per attempt. Do not edit a published version.
 */
export const GRAND_TEST_${num}_IDS: string[] = [
${body}
]
`)
const d: Record<string, number> = {}
entries.forEach((e) => (d[e.question.difficulty!] = (d[e.question.difficulty!] ?? 0) + 1))
console.log(`grandTest${num}.ts written`, d)
